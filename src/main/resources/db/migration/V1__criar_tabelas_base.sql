-- Contas de autenticacao (login por email e/ou Google).
-- A coluna "cpf" e legada: hoje guarda uma chave interna opaca, nunca um CPF.
CREATE TABLE auth_users (
                            id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                            cpf         VARCHAR(255) NOT NULL,
                            email       VARCHAR(255),
                            google_sub  VARCHAR(255),
                            senha       VARCHAR(255) NOT NULL,
                            role        VARCHAR(255),
                            CONSTRAINT uk_auth_users_cpf        UNIQUE (cpf),
                            CONSTRAINT uk_auth_users_email      UNIQUE (email),
                            CONSTRAINT uk_auth_users_google_sub UNIQUE (google_sub),
                            CONSTRAINT ck_auth_users_role       CHECK (role IN ('USUARIO', 'MEDICO', 'ATENDENTE'))
);

-- Pacientes
CREATE TABLE usuarios (
                          id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                          nome             VARCHAR(255) NOT NULL,
                          email            VARCHAR(255) NOT NULL,
                          telefone         VARCHAR(255),
                          usuario_auth_id  BIGINT NOT NULL,
                          CONSTRAINT uk_usuarios_email           UNIQUE (email),
                          CONSTRAINT uk_usuarios_usuario_auth_id UNIQUE (usuario_auth_id),
                          CONSTRAINT fk_usuarios_auth_users      FOREIGN KEY (usuario_auth_id) REFERENCES auth_users (id)
);

-- Medicos
CREATE TABLE medicos (
                         id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                         nome             VARCHAR(255) NOT NULL,
                         crm              VARCHAR(255) NOT NULL,
                         especialidade    VARCHAR(255) NOT NULL,
                         email            VARCHAR(255),
                         telefone         VARCHAR(255),
                         usuario_auth_id  BIGINT NOT NULL,
                         CONSTRAINT uk_medicos_crm             UNIQUE (crm),
                         CONSTRAINT uk_medicos_usuario_auth_id UNIQUE (usuario_auth_id),
                         CONSTRAINT fk_medicos_auth_users      FOREIGN KEY (usuario_auth_id) REFERENCES auth_users (id)
);

-- Atendentes
CREATE TABLE atendentes (
                            id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                            nome             VARCHAR(255) NOT NULL,
                            email            VARCHAR(255),
                            telefone         VARCHAR(255),
                            setor            VARCHAR(255) NOT NULL,
                            usuario_auth_id  BIGINT NOT NULL,
                            CONSTRAINT uk_atendentes_usuario_auth_id UNIQUE (usuario_auth_id),
                            CONSTRAINT fk_atendentes_auth_users      FOREIGN KEY (usuario_auth_id) REFERENCES auth_users (id)
);