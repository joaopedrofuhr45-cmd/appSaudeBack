CREATE TABLE consultas (
                           id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                           paciente_id    BIGINT       NOT NULL,
                           medico_id      BIGINT       NOT NULL,
                           tipo_consulta  VARCHAR(255) NOT NULL,
                           data_hora      TIMESTAMP(6) NOT NULL,
                           status         VARCHAR(255) NOT NULL,
                           observacao     VARCHAR(500),
                           CONSTRAINT fk_consultas_paciente FOREIGN KEY (paciente_id) REFERENCES usuarios (id),
                           CONSTRAINT fk_consultas_medico   FOREIGN KEY (medico_id)   REFERENCES medicos (id),
                           CONSTRAINT ck_consultas_status   CHECK (status IN ('AGENDADO', 'CONFIRMADO', 'EM_ESPERA', 'CANCELADO', 'CONCLUIDO'))
);

-- O Postgres nao cria indice automatico para chave estrangeira.
CREATE INDEX idx_consultas_paciente_id ON consultas (paciente_id);
CREATE INDEX idx_consultas_medico_id   ON consultas (medico_id);
CREATE INDEX idx_consultas_data_hora   ON consultas (data_hora);